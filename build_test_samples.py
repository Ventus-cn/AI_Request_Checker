def set_font(run, size=10.5, bold=False, color='000000'):
    run.font.name='宋体'; run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体'); run.font.size=Pt(size); run.bold=bold; run.font.color.rgb=RGBColor.from_string(color)

def shade(cell, fill):
    shd=OxmlElement('w:shd'); shd.set(qn('w:fill'), fill); cell._tc.get_or_add_tcPr().append(shd)

